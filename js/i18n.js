function detectLang() {
  try {
    const params = new URLSearchParams(window.location.search);
    const q = params.get("lang");
    if (q === "en" || q === "tr") return q;
  } catch (e) {
    /* ignore */
  }
  const stored = localStorage.getItem("ost_lang");
  if (stored === "en" || stored === "tr") return stored;
  return navigator.language && navigator.language.startsWith("tr")
    ? "tr"
    : "en";
}

export let currentLang = detectLang();

export function setLanguage(lang) {
  if (lang !== "en" && lang !== "tr") lang = "en";
  currentLang = lang;
  localStorage.setItem("ost_lang", lang);
  try {
    const url = new URL(window.location.href);
    url.searchParams.set("lang", lang);
    history.replaceState({}, "", url);
  } catch (e) {}
  updateDOM();
}

export function t(key) {
  const dict = translations[currentLang] || translations.en;
  return dict[key] || (translations.en && translations.en[key]) || key;
}

export function updateDOM() {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const translation = t(key);
    if (el.tagName === "INPUT" || el.tagName === "TEXTAREA") {
      if (el.hasAttribute("placeholder"))
        el.setAttribute("placeholder", translation);
    } else {
      el.textContent = translation;
    }
  });

  document.documentElement.lang = currentLang;

  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    el.setAttribute("title", t(key));
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria-label");
    el.setAttribute("aria-label", t(key));
  });

  document.querySelectorAll("[data-i18n-aria-label]").forEach((el) => {
    const key = el.getAttribute("data-i18n-aria-label");
    el.setAttribute("aria-label", t(key));
  });

  const langToggleBtn = document.getElementById("lang-toggle-btn");
  if (langToggleBtn) {
    langToggleBtn.textContent = currentLang === "en" ? "TR" : "EN";
  }

  window.dispatchEvent(
    new CustomEvent("languageChanged", { detail: { lang: currentLang } }),
  );
}
